COMMENT ON COLUMN work_orders.est_cost IS 'Estimated repair cost in USD. Deterministic floor refined by the AI generator when AI_WORK_ORDER=1.';

-- ---------------------------------------------------------------------------
-- 2. wo_source. Provenance of the work order's crew/materials/minutes/cost.
--    'ai'. Generated by the Gemini work-order generator
