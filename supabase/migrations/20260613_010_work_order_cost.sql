-- ---------------------------------------------------------------------------
-- 1. est_cost. Estimated total repair cost in whole USD.
--    Deterministic floor = labor_rate * (est_minutes / 60) + material_cost.
--    The AI work-order generator may refine this; null when never computed.
-- ---------------------------------------------------------------------------
